// Tentukan apakah menu item ini aktif (exact atau prefix match)
function isMenuActive(string $itemPage, string $currentPage): bool
{
  if ($itemPage === $currentPage)
    return true;
  // Aktifkan parent jika currentPage adalah child-nya (contoh: criteria/edit → criteria)
  return str_starts_with($currentPage, $itemPage . '/');
}

